    /// 차량 별명/모델/색상/연식 기반 해시태그 추출
    /// - Note: 별명이 있으면 가장 먼저 추가 (사용자가 정한 명명이라 식별성 최고)
    /// - Note: 모델명에 공백이 들어있으면 마지막 단어만 사용 (예: "기아 K8" → "#K8")
    static func tagsFromCar(model: String?, color: String?, year: Int? = nil, nickname: String? = nil) -> [String] {
        var tags: [String] = []
        // ① 별명 — 사용자가 직접 부여한 명명을 우선
        if let nick = nickname?.trimmingCharacters(in: .whitespacesAndNewlines), !nick.isEmpty {
            // 공백 제거 (해시태그 단일 토큰으로)
            let normalized = nick.components(separatedBy: .whitespacesAndNewlines).joined()
            if !normalized.isEmpty {
                tags.append("#\(normalized)")
            }
        }
        // ② 모델
        if let model = model, !model.isEmpty {
            // 첫 단어만 사용 — 너무 긴 차량명은 해시태그로 부적절
            let normalized = model.split(separator: " ").last.map(String.init) ?? model
            tags.append("#\(normalized)")
        }
        // ③ 색상
        if let color = color, !color.isEmpty {
            tags.append("#\(color)")
        }
        // ④ 연식
        if let year = year, year > 1980 {
            tags.append("#\(year)년식")
        }
        return tags
    }
